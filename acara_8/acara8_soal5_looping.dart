void main() {
  print("=========================================");
  print("      ACARA 8 - SOAL 5 (LOOPING)         ");
  print("=========================================\n");

  print("LOOPING PERTAMA (INCREMENT)");
  int i = 2;
  while (i <= 20) {
    print("$i - I love coding");
    i += 2;
  }

  print("\nLOOPING KEDUA (DECREMENT)");
  int j = 20;
  while (j >= 2) {
    print("$j - I will become a mobile developer");
    j -= 2;
  }

  print("=========================================");
}